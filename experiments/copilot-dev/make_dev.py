"""Generates the Copilot dev plugin `pigeon-dev` from the production plugin, for host tests.

The copy differs only in its names (plugin, MCP server and extension `pigeon-dev`), the frozen test
build, the isolated port 49473 and the disposable database (see ../host-test/README.md).
Run: python -I experiments/copilot-dev/make_dev.py
"""
import json, os, shutil

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SOURCE = os.path.join(ROOT, 'integrations', 'copilot-plugin')
TARGET = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'pigeon-dev')
EXE = os.path.join(ROOT, 'artifacts', 'host-test', 'bin', 'pigeon.exe')
DB = os.path.join(ROOT, 'artifacts', 'host-test', 'data', 'messages.db')

shutil.rmtree(TARGET, ignore_errors=True)
os.makedirs(os.path.join(TARGET, 'extensions', 'pigeon-dev'))
os.makedirs(os.path.join(TARGET, 'skills', 'connect'))

manifest = json.load(open(os.path.join(SOURCE, 'plugin.json'), encoding='utf-8'))
manifest['name'] = 'pigeon-dev'
manifest['version'] += '.dev.1'
manifest['description'] = 'Development copy of the Pigeon plugin for host tests: the frozen test build on the isolated port 49473.'
json.dump(manifest, open(os.path.join(TARGET, 'plugin.json'), 'w', encoding='utf-8'), indent=2)

mcp = json.load(open(os.path.join(SOURCE, '.mcp.json'), encoding='utf-8'))
server = mcp['mcpServers'].pop('pigeon')
server['command'] = EXE
server['env'] = {'PIGEON_RUNTIME': 'copilot', 'PIGEON_PORT': '49473', 'PIGEON_DATABASE': DB}
mcp['mcpServers']['pigeon-dev'] = server
json.dump(mcp, open(os.path.join(TARGET, '.mcp.json'), 'w', encoding='utf-8'), indent=2)

extension = open(os.path.join(SOURCE, 'extensions', 'pigeon', 'extension.mjs'), encoding='utf-8').read()
for old, new in [('const port = process.env.PIGEON_PORT ?? "49372"', 'const port = "49473"'),
                 ('const server = "pigeon"', 'const server = "pigeon-dev"')]:
    assert old in extension, old
    extension = extension.replace(old, new, 1)
with open(os.path.join(TARGET, 'extensions', 'pigeon-dev', 'extension.mjs'), 'w', encoding='utf-8', newline='\n') as f:
    f.write('// GENERATED by experiments/copilot-dev/make_dev.py for host tests; do not edit.\n' + extension)
shutil.copyfile(os.path.join(SOURCE, 'extensions', 'pigeon', 'waker.mjs'), os.path.join(TARGET, 'extensions', 'pigeon-dev', 'waker.mjs'))

skill = open(os.path.join(SOURCE, 'skills', 'connect', 'SKILL.md'), encoding='utf-8').read()
skill = skill.replace('\n---\n\n', '\n---\n\nDevelopment copy for Pigeon host tests: use the **pigeon-dev** tools; they talk to the isolated test service on port 49473.\n\n', 1)
with open(os.path.join(TARGET, 'skills', 'connect', 'SKILL.md'), 'w', encoding='utf-8', newline='\n') as f:
    f.write(skill)
print('wrote', TARGET)
