"""Generates the OpenCode dev plugin `pigeon-dev` from the production plugin, for host tests.

The copy differs only in its names, the frozen test build, the isolated port 49473 and the
disposable database (see ../host-test/README.md). Run: python -I experiments/opencode-dev/make_dev.py
"""
import json, os, shutil

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SOURCE = os.path.join(ROOT, 'integrations', 'opencode-plugin', 'pigeon')
TARGET = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'pigeon-dev')
# json.dumps gives a quoted TypeScript string literal with the backslashes escaped.
EXE = json.dumps(os.path.join(ROOT, 'artifacts', 'host-test', 'bin', 'pigeon.exe'))
DB = json.dumps(os.path.join(ROOT, 'artifacts', 'host-test', 'data', 'messages.db'))

server = open(os.path.join(SOURCE, 'server.ts'), encoding='utf-8').read()
for old, new in [
    ('id: "pigeon",', 'id: "pigeon-dev",'),
    ('editor.set("pigeon", {', 'editor.set("pigeon-dev", {'),
    ('process.env.PIGEON_PORT ?? "49372"', '"49473"'),
    ('command: ["pigeon", "mcp"],', f'command: [{EXE}, "mcp"],'),
    ('environment: { PIGEON_RUNTIME: "opencode", PIGEON_PORT: port },', f'environment: {{ PIGEON_RUNTIME: "opencode", PIGEON_PORT: port, PIGEON_DATABASE: {DB} }},'),
]:
    assert old in server, old
    server = server.replace(old, new, 1)
os.makedirs(TARGET, exist_ok=True)
with open(os.path.join(TARGET, 'server.ts'), 'w', encoding='utf-8', newline='\n') as f:
    f.write('// GENERATED by experiments/opencode-dev/make_dev.py for host tests; do not edit.\n' + server)
shutil.copyfile(os.path.join(SOURCE, 'waker.ts'), os.path.join(TARGET, 'waker.ts'))
print('wrote', TARGET)
